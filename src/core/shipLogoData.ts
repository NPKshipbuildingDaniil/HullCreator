export const CAD_BOUNDS = { minX: 107810, maxX: 107978, minY: -103826, maxY: -103684 };
export const TARGET = 1000;
export const avail = TARGET - 80 * 2;
export const cadW = CAD_BOUNDS.maxX - CAD_BOUNDS.minX;
export const cadH = CAD_BOUNDS.maxY - CAD_BOUNDS.minY;
export const baseScale = avail / Math.max(cadW, cadH);
export const offsetX = (TARGET - cadW * baseScale) / 2;
export const offsetY = (TARGET - cadH * baseScale) / 2;

export function cadToWorld(x: number, y: number): [number, number] {
  return [offsetX + (x - CAD_BOUNDS.minX) * baseScale, offsetY + (CAD_BOUNDS.maxY - y) * baseScale];
}

export function generateClampedKnots(n: number, p: number): number[] {
  const knots: number[] = [];
  const m = n + p;
  for (let i = 0; i <= m; i++) {
    if (i <= p) knots.push(0);
    else if (i >= m - p) knots.push(1);
    else knots.push((i - p) / (n - p));
  }
  return knots;
}

export function evalBSpline(u: number, p: number, knots: number[], pts: [number, number][]): [number, number] {
  const n = pts.length - 1;
  const m = knots.length;
  if (u <= knots[p]) return [pts[0][0], pts[0][1]];
  if (u >= knots[m - 1 - p]) return [pts[n][0], pts[n][1]];
  let k = p;
  while (k < m - 1 - p && knots[k + 1] <= u) k++;
  const d: [number, number][] = [];
  for (let j = 0; j <= p; j++) d[j] = [pts[k - p + j][0], pts[k - p + j][1]];
  for (let r = 1; r <= p; r++) {
    for (let j = p; j >= r; j--) {
      const i = k - p + j;
      const denom = knots[i + p - r + 1] - knots[i];
      const alpha = denom !== 0 ? (u - knots[i]) / denom : 0;
      d[j][0] = (1 - alpha) * d[j - 1][0] + alpha * d[j][0];
      d[j][1] = (1 - alpha) * d[j - 1][1] + alpha * d[j][1];
    }
  }
  return d[p];
}

export function buildRibbonPath(item: SplineItem, pts: [number, number][]): string {
  const p = Math.min(3, pts.length - 1);
  const knots = generateClampedKnots(pts.length, p);
  const SAMPLES = 60;
  const spine: [number, number][] = [];
  for (let i = 0; i <= SAMPLES; i++) {
    const u = i / SAMPLES;
    const cadPt = evalBSpline(u, p, knots, pts);
    spine.push(cadToWorld(cadPt[0], cadPt[1]));
  }
  const left: [number, number][] = [];
  const right: [number, number][] = [];
  for (let i = 0; i <= SAMPLES; i++) {
    const t = i / SAMPLES;
    const cur = spine[i];
    let tx: number, ty: number;
    if (i === 0) {
      tx = spine[1][0] - cur[0];
      ty = spine[1][1] - cur[1];
    } else if (i === SAMPLES) {
      tx = cur[0] - spine[i - 1][0];
      ty = cur[1] - spine[i - 1][1];
    } else {
      tx = spine[i + 1][0] - spine[i - 1][0];
      ty = spine[i + 1][1] - spine[i - 1][1];
    }
    const len = Math.hypot(tx, ty) || 1;
    const nx = -ty / len;
    const ny = tx / len;
    const w = item.wStart + (item.wEnd - item.wStart) * t;
    const r = w / 2;
    left.push([cur[0] + nx * r, cur[1] + ny * r]);
    right.push([cur[0] - nx * r, cur[1] - ny * r]);
  }
  let d = 'M ' + left[0][0].toFixed(1) + ' ' + left[0][1].toFixed(1);
  for (let i = 1; i <= SAMPLES; i++) d += ' L ' + left[i][0].toFixed(1) + ' ' + left[i][1].toFixed(1);
  d += ' L ' + right[SAMPLES][0].toFixed(1) + ' ' + right[SAMPLES][1].toFixed(1);
  for (let i = SAMPLES - 1; i >= 0; i--) d += ' L ' + right[i][0].toFixed(1) + ' ' + right[i][1].toFixed(1);
  d += ' L ' + left[0][0].toFixed(1) + ' ' + left[0][1].toFixed(1) + ' Z';
  return d;
}

